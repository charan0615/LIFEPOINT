-- LIFEPOINT Relational Database Schema
-- Compatible with PostgreSQL and H2

CREATE TABLE IF NOT EXISTS profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255),
    currency VARCHAR(10) DEFAULT 'INR',
    xp INT DEFAULT 0,
    level INT DEFAULT 1,
    total_saved_by_habits DOUBLE PRECISION DEFAULT 0.0
);

CREATE TABLE IF NOT EXISTS habit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_email VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    frequency VARCHAR(50) DEFAULT 'DAILY',
    category VARCHAR(50) DEFAULT 'Personal',
    completed_on DATE,
    current_streak INT DEFAULT 0,
    best_streak INT DEFAULT 0,
    total_completions INT DEFAULT 0,
    money_saver BOOLEAN DEFAULT FALSE,
    saved_amount DOUBLE PRECISION DEFAULT 0.0,
    linked_goal_id BIGINT
);

CREATE TABLE IF NOT EXISTS habit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_email VARCHAR(255) NOT NULL,
    habit_id BIGINT NOT NULL,
    habit_title VARCHAR(255),
    completed_date DATE NOT NULL,
    saved_amount DOUBLE PRECISION DEFAULT 0.0
);

CREATE TABLE IF NOT EXISTS expense (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_email VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    category VARCHAR(100) NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    spent_on DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS income (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_email VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    category VARCHAR(100) NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    received_on DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS budget (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_email VARCHAR(255) NOT NULL,
    category VARCHAR(100) NOT NULL,
    monthly_limit DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS savings_goal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_email VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    target_amount DOUBLE PRECISION NOT NULL,
    current_amount DOUBLE PRECISION DEFAULT 0.0,
    target_date DATE,
    category VARCHAR(100) DEFAULT 'General',
    color VARCHAR(50) DEFAULT '#6366f1',
    completed BOOLEAN DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS achievement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_email VARCHAR(255) NOT NULL,
    badge_code VARCHAR(100) NOT NULL,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(500),
    icon VARCHAR(50),
    unlocked_on DATE NOT NULL
);

-- Performance and isolation indexes
CREATE INDEX IF NOT EXISTS idx_habit_owner ON habit(owner_email);
CREATE INDEX IF NOT EXISTS idx_expense_owner_date ON expense(owner_email, spent_on);
CREATE INDEX IF NOT EXISTS idx_income_owner_date ON income(owner_email, received_on);
CREATE INDEX IF NOT EXISTS idx_budget_owner ON budget(owner_email);
CREATE INDEX IF NOT EXISTS idx_goal_owner ON savings_goal(owner_email);
CREATE INDEX IF NOT EXISTS idx_log_owner_date ON habit_log(owner_email, completed_date);
CREATE INDEX IF NOT EXISTS idx_achievement_owner ON achievement(owner_email);
